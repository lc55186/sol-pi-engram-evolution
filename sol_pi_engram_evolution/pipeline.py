def _load_module(name, rel_path):
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), rel_path)
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


class WikiModeEngine:
    """Wiki Mode：结构化知识库输出引擎

    将图谱存储中的节点和关系组织为 Wiki 风格页面：
    - 节点页面（NodePage）：每个节点一个页面，含标题/描述/关系/引用
    - 关系图谱页面（RelationGraph）：可视化的关系拓扑
    - 时间线页面（Timeline）：按时间排序的事件链
    - 分类索引（CategoryIndex）：按节点类型分类
    """

    def __init__(self, store=None):
        self.store = store

    def generate_node_page(self, node: dict) -> str:
        """生成节点 Wiki 页面（Markdown 格式）"""
        lines = [
            f"# {node.get('title', 'Untitled Node')}",
            "",
            f"**Type**: `{node.get('node_type', 'unknown')}`",
            f"**ID**: `{node.get('node_id', '')}`",
            f"**Created**: {node.get('created_at', 'N/A')}",
            f"**Updated**: {node.get('updated_at', 'N/A')}",
            "",
            "## Description",
            "",
            node.get('description', '*No description*'),
            "",
        ]

        # 节点特有字段
        if node.get('node_type') == 'task':
            lines.extend([
                "## Task Details",
                "",
                f"- **Status**: {node.get('status', 'unknown')}",
                f"- **Priority**: {node.get('priority', 'N/A')}",
                "",
            ])
        elif node.get('node_type') == 'event':
            lines.extend([
                "## Event Details",
                "",
                f"- **Event Type**: {node.get('event_type', 'unknown')}",
                f"- **Outcome**: {node.get('outcome', 'N/A')}",
                "",
            ])

        # 实体列表
        entities = node.get('entities', [])
        if entities:
            lines.extend([
                "## Entities",
                "",
            ])
            for e in entities:
                lines.append(f"- {e}")
            lines.append("")

        # 关联节点（关系）
        if self.store:
            relations = self.store.get_relations_for_node(node.get('node_id', ''))
            if relations:
                lines.extend([
                    "## Relations",
                    "",
                ])
                for rel in relations:
                    target_id = (rel['target_node_id']
                                 if rel['source_node_id'] == node.get('node_id', '')
                                 else rel['source_node_id'])
                    target_node = self.store.get_node_by_id(target_id)
                    target_title = (target_node.get('title', 'Unknown')
                                    if target_node else 'Unknown')
                    rel_type = rel.get('relation_type', 'related_to')
                    lines.append(f"- **{rel_type}** → [{target_title}]({target_id})")
                lines.append("")

        lines.extend([
            "---",
            f"*Generated by SoL-Pi Wiki Mode at {datetime.now().strftime('%Y-%m-%d %H:%M')}*",
        ])

        return "\n".join(lines)

    def generate_timeline_page(self, limit: int = 20) -> str:
        """生成时间线 Wiki 页面"""
        if not self.store:
            return "# Timeline\n\n*No store available*"

        events = []
        for node in self.store.get_all_nodes():
            if node.get('node_type') == 'event':
                events.append(node)
        events.sort(key=lambda x: x.get('created_at', ''), reverse=True)
        events = events[:limit]

        lines = [
            "# Timeline",
            "",
            f"**Total Events**: {len(events)}",
            "",
            "| Time | Event | Outcome |",
            "|------|-------|---------|",
        ]
        for e in events:
            title = e.get('title', 'Untitled')[:50]
            outcome = (e.get('outcome', '') or '')[:40]
            ts = e.get('created_at', 'N/A')[:19]
            lines.append(f"| {ts} | {title} | {outcome} |")

        return "\n".join(lines)

    def generate_category_index(self) -> str:
        """生成分类索引 Wiki 页面"""
        if not self.store:
            return "# Category Index\n\n*No store available*"

        categories = {}
        for node in self.store.get_all_nodes():
            ntype = node.get('node_type', 'unknown')
            if ntype not in categories:
                categories[ntype] = []
            categories[ntype].append(node)

        lines = [
            "# Category Index",
            "",
            f"**Total Nodes**: {sum(len(v) for v in categories.values())}",
            "",
        ]
        for ntype, nodes in categories.items():
            lines.extend([
                f"## {ntype.title()} ({len(nodes)})",
                "",
            ])
            for n in nodes:
                title = n.get('title', 'Untitled')[:60]
                nid = n.get('node_id', '')
                lines.append(f"- [{title}]({nid})")
            lines.append("")

        return "\n".join(lines)

    def generate_relation_graph(self) -> str:
        """生成关系图谱 Wiki 页面（Mermaid 格式）"""
        if not self.store:
            return "# Relation Graph\n\n*No store available*"

        lines = [
            "# Relation Graph",
            "",
            "```mermaid",
            "graph TD",
        ]

        seen_nodes = set()
        for node in self.store.get_all_nodes():
            nid = node.get('node_id', '')
            title = (node.get('title', 'Unknown')[:30]).replace('"', "'")
            seen_nodes.add(nid)
            lines.append(f'    {nid}["{title}"]')

        for node in self.store.get_all_nodes():
            nid = node.get('node_id', '')
            relations = self.store.get_relations_for_node(nid)
            for rel in relations:
                if rel.get('source_node_id') == nid:
                    target = rel.get('target_node_id', '')
                    if target in seen_nodes:
                        rel_type = rel.get('relation_type', 'related')
                        lines.append(f"    {nid} -->|{rel_type}| {target}")

        lines.extend([
            "```",
            "",
            "---",
            f"*Auto-generated at {datetime.now().strftime('%Y-%m-%d %H:%M')}*",
        ])
        return "\n".join(lines)


class ReACTAgentMode:
    """ReACT Agent Mode：Reasoning + Acting 循环执行

    基于 ReACT 框架（Yao et al., 2022）：
    - Thought：推理当前状态，决定下一步行动
    - Action：执行工具调用（搜索/查询/归档/评估）
    - Observation：观察结果，更新认知
    - 循环直到任务完成或达到最大轮次
    """

    def __init__(self, pipeline: 'EvolutionPipeline'):
        self.pipeline = pipeline
        self.max_iterations = 10
        self.log: list[dict] = []

    def execute(self, query: str, context: dict = None) -> dict:
        """执行 ReACT 循环"""
        self.log = []
        current_context = context or {"query": query, "facts": [], "candidates": []}
        iteration = 0
        final_answer = None

        while iteration < self.max_iterations:
            iteration += 1

            # === Thought：推理下一步 ===
            thought = self._reasoning_step(query, current_context, iteration)
            self.log.append({
                "step": iteration,
                "type": "thought",
                "content": thought,
            })

            # 如果推理认为可以结束，提取最终答案
            if thought.get("should_finish"):
                final_answer = thought.get("answer")
                break

            # === Action：执行工具 ===
            action = self._decide_action(thought, current_context)
            self.log.append({
                "step": iteration,
                "type": "action",
                "content": action,
            })

            if not action:
                break

            # === Observation：执行并观察结果 ===
            observation = self._execute_action(action)
            self.log.append({
                "step": iteration,
                "type": "observation",
                "content": observation,
            })

            # 更新上下文
            current_context["facts"].extend(observation.get("new_facts", []))
            current_context["candidates"].extend(observation.get("candidates", []))

            if observation.get("terminal"):
                final_answer = observation.get("result")
                break

        return {
            "query": query,
            "iterations": iteration,
            "final_answer": final_answer,
            "context": current_context,
            "reasoning_log": self.log,
        }

    def _reasoning_step(self, query: str, context: dict, iteration: int) -> dict:
        """推理步骤：分析当前状态，决定下一步"""
        facts = context.get("facts", [])
        candidates = context.get("candidates", [])

        # 简单启发式推理逻辑
        if not facts and not candidates:
            return {
                "reasoning": "No facts yet. Need to search for relevant information.",
                "should_finish": False,
                "next_action": "search",
            }

        if candidates and len(candidates) >= 3:
            return {
                "reasoning": f"Found {len(candidates)} candidate nodes. Sufficient to synthesize answer.",
                "should_finish": True,
                "answer": self._synthesize_answer(query, candidates),
            }

        if iteration >= 3 and candidates:
            return {
                "reasoning": f"Iteration {iteration}: Have {len(candidates)} candidates, stopping.",
                "should_finish": True,
                "answer": self._synthesize_answer(query, candidates),
            }

        return {
            "reasoning": f"Iteration {iteration}: Need more information.",
            "should_finish": False,
            "next_action": "traverse",
        }

    def _decide_action(self, thought: dict, context: dict) -> dict | None:
        """根据推理决定下一步行动"""
        next_action = thought.get("next_action", "search")

        if next_action == "search":
            return {"tool": "graph_search", "query": context.get("query", "")}
        elif next_action == "traverse":
            candidates = context.get("candidates", [])
            if candidates:
                node = candidates[0]
                return {"tool": "traverse_relations", "node_id": node.get("node_id", "")}
            return {"tool": "graph_search", "query": context.get("query", "")}
        elif next_action == "archive":
            return {"tool": "archive", "content": context.get("query", "")}
        elif next_action == "evaluate":
            candidates = context.get("candidates", [])
            if candidates:
                return {"tool": "evaluate", "node_id": candidates[0].get("node_id", "")}

        return None

    def _execute_action(self, action: dict) -> dict:
        """执行行动并返回观察结果"""
        tool = action.get("tool", "")

        if tool == "graph_search":
            if self.pipeline.graph_retriever:
                results = self.pipeline.graph_retriever.retrieve(
                    action.get("query", ""), top_k=5
                )
                candidates = [{"node_id": n.get("node_id"), "title": n.get("title", ""),
                               "score": s} for n, s in results]
                return {
                    "tool": tool,
                    "new_facts": [f"Found {len(candidates)} relevant nodes"],
                    "candidates": candidates,
                    "terminal": len(candidates) == 0,
                }

        elif tool == "traverse_relations":
            if self.pipeline.graph_store:
                relations = self.pipeline.graph_store.get_relations_for_node(
                    action.get("node_id", "")
                )
                new_facts = [f"Found {len(relations)} relations from node"]
                candidates = []
                for rel in relations:
                    target_id = (rel['target_node_id']
                                 if rel['source_node_id'] == action.get("node_id", "")
                                 else rel['source_node_id'])
                    target = self.pipeline.graph_store.get_node_by_id(target_id)
                    if target:
                        candidates.append({
                            "node_id": target.get("node_id"),
                            "title": target.get("title", ""),
                            "score": 0.5,
                        })
                return {
                    "tool": tool,
                    "new_facts": new_facts,
                    "candidates": candidates,
                    "terminal": len(relations) == 0,
                }

        elif tool == "evaluate":
            if self.pipeline.value_evaluator:
                node = self.pipeline.graph_store.get_node_by_id(
                    action.get("node_id", "")
                ) if self.pipeline.graph_store else None
                if node:
                    score = self.pipeline.value_evaluator.evaluate(node)
                    return {
                        "tool": tool,
                        "new_facts": [f"Node evaluation score: {score:.2f}"],
                        "candidates": [{"node_id": node.get("node_id"),
                                        "score": score}],
                        "terminal": False,
                    }

        return {"tool": tool, "new_facts": [], "candidates": [], "terminal": True}

    def _synthesize_answer(self, query: str, candidates: list[dict]) -> str:
        """基于候选节点合成最终答案"""
        if not candidates:
            return f"No relevant information found for: {query}"

        parts = [f"Based on {len(candidates)} relevant nodes:"]
        for i, c in enumerate(candidates[:5], 1):
            title = c.get("title", "Untitled")
            score = c.get("score", 0)
            parts.append(f"  {i}. {title} (relevance: {score:.3f})")
        return "\n".join(parts)


class EvolutionPipeline:
    """进化系统主 Pipeline（V0.3 增强：Wiki Mode + ReACT Agent Mode）"""

    def __init__(self, config: dict[str, Any] = None):
        self.config = config or {}
        from logger import get_logger, log_pipeline_event
        self.logger = get_logger("pipeline")
        self._log_pipeline_event = log_pipeline_event

        # 模块引用
        self.graph_store = None
        self.observation_pack = None
        self.graph_extractor = None
        self.evidence_verifier = None
        self.graph_retriever = None
        self.context_manager = None
        self.action_fusion = None
        self.context_compactor = None
        self.value_evaluator = None
        self.router = None
        self.evolution_interface = None
        self.role_router = None
        self.knowledge_isolation = None
        self.engram = None
        self.engram_bridge = None
        self.a2a_adapter = None

        # V0.3: Wiki Mode + ReACT Agent Mode
        self.wiki_engine = WikiModeEngine()
        self.react_agent = ReACTAgentMode(self)

        self._init_modules()

    def _init_modules(self):
        """初始化所有模块（优雅降级）"""
        errors = []

